# -*- coding: utf-8 -*-
"""
Сборка планшетов фракций «Нефтяные войны».

    python3 Сборка.py              собрать все фракции из Данные/*.json
    python3 Сборка.py Клонэйд      собрать только те, чьё имя содержит «Клонэйд»

Что делает: берёт Шаблон.html, подставляет содержимое в помеченные слоты
(<!--#имя--> ... <!--/#имя-->) и пишет «Планшет — <Фракция>.html» рядом.

Шаблон — валидный самостоятельный файл: его можно открыть, он покажет готовый
планшет с демо-содержимым. Генератор это содержимое заменяет, ничего больше
в шаблоне не трогая. Поэтому править оформление можно прямо в шаблоне, а
скрипт переписывать не нужно.

Единственное, что скрипт считает сам, — вертикальная раскладка блоков свойств
(раздел «РАСКЛАДКА» ниже). Всё остальное — прямая подстановка.
"""
import io, json, math, os, re, sys, html

# Проверка кавычек (D-075): общая для всех печатных компонентов, лежит в print/.
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from check_quotes import проверить as проверить_кавычки

ROOT = os.path.dirname(os.path.abspath(__file__))
DATA_DIR = os.path.join(ROOT, 'Данные')
TPL_FILE = os.path.join(ROOT, 'Шаблон.html')

# ══════════════════════════════════════════════════════════════ ГЕОМЕТРИЯ
# Те же числа, что в :root шаблона. Держать синхронно: скрипт считает по ним
# раскладку свойств и координаты линий-привязок.
CARD_W, CARD_H = 240.0, 170.0
PAD, GAP = 6.0, 4.0
ROW_TRACK, ROW_BODY = 18.0, 136.0
COL_LEFT, COL_ABIL, COL_TABLE = 66.0, 85.0, 69.0

BODY_TOP = PAD + ROW_TRACK + GAP                 # 28 мм — верх колонок
X_ABIL_R = PAD + COL_LEFT + GAP + COL_ABIL       # 161 мм — правый край колонки свойств
X_TABLE  = X_ABIL_R + GAP                        # 165 мм — левый край таблицы

# Высота силуэта отряда. Рекрут визуально мельче всех, боевой робот крупнее всех —
# соотношения взяты от реальных размеров миниатюр, но сжаты, чтобы строки таблицы
# не разъезжались. Значение поля «размер» в данных.
ВЫСОТА_ИКОНКИ = {'пехота': 9.0, 'офицер': 10.5, 'машина': 12.0, 'мех': 12.5, 'робот': 14.5}

PT = 25.4 / 72.0


def высота_строки(pt, lh=1.22):
    """Высота строки текста в мм."""
    return pt * PT * lh


def символов_в_строке(ширина_мм, pt):
    """Грубая оценка: сколько символов влезает в строку. 0.50 — средняя ширина
    знака относительно кегля для Arial с кириллицей, проверено на этих текстах."""
    return max(8, int((ширина_мм - 2.0) / (pt * PT * 0.50)))


# ══════════════════════════════════════════════════════════════ ТЕКСТ
def esc(s):
    """Экранирование для текста внутри тегов."""
    return html.escape(str(s), quote=False)


def attr(s):
    """Экранирование для значения атрибута. Отдельная функция не для красоты:
    имена отрядов содержат кавычки («Жнец», ББМП «Саранча»), и без неё рвётся
    и сам атрибут, и селектор, который по нему ищет."""
    return html.escape(str(s), quote=True)


СИМВОЛ = re.compile(r'\{([^}]{1,12})\}')


def текст(s):
    """Экранирует HTML и разворачивает {Q} в символ региона шрифтом Oil Wars.
    Внутри фигурных скобок — буквы раскладки этого шрифта: Q нефть, W огонь, E руда."""
    return СИМВОЛ.sub(r'<span class="sym">\1</span>', esc(s))


# ══════════════════════════════════════════════════════════════ РАСКЛАДКА
def раскладка_таблицы(отряды):
    """Считает, на какой высоте окажется подпись каждого отряда.
    Нужно, чтобы притянуть к нему блок свойства. Возвращает (высота, {имя: y})."""
    y, центры = 4.6, {}                                   # 4.6 — шапка таблицы
    for r in отряды:
        if 'имя' in r:
            h = ВЫСОТА_ИКОНКИ[r['размер']]
            центры[r['имя']] = y + h + 2.0                # середина подписи
            y += h + 5.8
        elif r.get('разделитель'):
            y += 2.7
        else:
            n = max(1, math.ceil(len(r['сноска']) / символов_в_строке(COL_TABLE, 9)))
            y += n * высота_строки(9) + 1.6
    return y, центры


def раскладка_свойств(свойства, центры):
    """Расставляет блоки свойств по вертикали: каждый тянется к своему отряду,
    но порядок сверху вниз не нарушается. Если не влезло — поджимаем добавленные
    отступы; если осталось место — раздаём его между блоками.
    Возвращает список отступов сверху (margin-top) и список вертикальных центров
    заголовков — для запасных линий-привязок."""
    W = символов_в_строке(COL_ABIL, 9)
    высоты = []
    for p in свойства:
        строк = sum(max(1, math.ceil(len(x) / W)) for x in p['текст'])
        высоты.append(0.8 + высота_строки(12.5, 0.98) + высота_строки(9, 1.15)
                      + 0.6 + строк * высота_строки(9))

    верх, поток = [], 0.0
    for i, p in enumerate(свойства):
        цель = центры.get(p.get('отряд')) if p.get('притяжение', True) else None
        t = None if цель is None else цель - высоты[i] / 2.0
        top = поток if (i == 0 or t is None) else max(поток, t)
        верх.append(top)
        поток = top + высоты[i] + 3.0

    перелив = поток - 3.0 - ROW_BODY
    if перелив > 0:                                        # поджимаем добавленные зазоры
        добавка = [верх[i] - (верх[i-1] + высоты[i-1] + 3.0) if i else 0
                   for i in range(len(свойства))]
        всего = sum(добавка)
        if всего > 0:
            k = max(0.0, 1 - перелив / всего)
            бег = 0.0
            for i in range(len(свойства)):
                бег = бег + добавка[i] * k if i else 0.0
                верх[i] = бег
                бег += высоты[i] + 3.0
    остаток = ROW_BODY - (поток - 3.0)
    if остаток > 12.0 and len(свойства) > 1:               # лишнее место делим между блоками
        шаг = (остаток * 0.55) / (len(свойства) - 1)
        for i in range(1, len(свойства)):
            верх[i] += шаг * i

    # Отступ в разметке включает и сам зазор 3 мм: CSS своего зазора между
    # блоками не даёт. Без этого блоки без добавки стояли вплотную.
    отступы = [верх[0]] + [верх[i] - (верх[i-1] + высоты[i-1])
                           for i in range(1, len(свойства))]
    заголовки = [BODY_TOP + верх[i] + 0.8 + высота_строки(12.5, 0.98) / 2.0
                 for i in range(len(свойства))]
    return отступы, заголовки, max(0.0, перелив)


# ══════════════════════════════════════════════════════════════ РАЗМЕТКА
def блок_подготовки(p):
    return (
        '          <div class="prep-row"><b>Стартовый регион:</b> <span>%s</span></div>\n'
        '          <div class="prep-row"><b>Очередь:</b> <span>%s</span>'
        ' · <b>Запас нефти:</b> <span>%s</span></div>\n'
        '          <div class="prep-note">%s</div>'
        % (текст(p['регион']), текст(p['очередь']), текст(p['нефть']), текст(p['примечание'])))


def блоки_шагов(блоки):
    out = []
    for b in блоки:
        # «внизу»: true — блок прижат к низу левой колонки (D-060)
        кл = ' class="pin-bottom"' if b.get('внизу') else ''
        заг = ('\n          <div class="block-title">%s</div>' % esc(b['заголовок'])
               if b.get('заголовок') else '')
        if 'текст' in b:                                   # блок без нумерации
            тело = ''.join('\n            <p>%s</p>' % текст(s) for s in b['текст'])
            out.append('        <div%s>%s\n          <div class="block-text">%s\n          </div>\n        </div>'
                       % (кл, заг, тело))
            continue
        шаги = ''.join('\n            <li>%s</li>' % текст(s) for s in b['шаги'])
        out.append('        <div%s>%s\n'
                   '          <ol class="steps">%s\n          </ol>\n        </div>'
                   % (кл, заг, шаги))
    return '\n'.join(out)


def блоки_свойств(свойства, отступы):
    out = []
    for p, m in zip(свойства, отступы):
        тело = ''.join('<div>%s</div>' % текст(x) for x in p['текст'])
        тяга = '' if p.get('притяжение', True) else ' data-pull="no"'   # D-060
        if p.get('смещение'):                                          # D-073
            тяга += ' data-shift="%s"' % float(p['смещение'])
        out.append('        <div class="ability" data-link="%s"%s style="margin-top: %.1fmm;">\n'
                   '          <div class="ability-name">%s</div>\n'
                   '          <div class="ability-note">%s</div>\n'
                   '          <div class="ability-text">%s</div>\n'
                   '        </div>'
                   % (attr(p.get('отряд', '')), тяга, max(0.0, m),
                      esc(p['заголовок']), esc(p['фаза']), тело))
    return '\n'.join(out)


def строки_таблицы(отряды):
    out = []
    for i, r in enumerate(отряды):
        if r.get('разделитель'):
            out.append('            <tr class="sep"><td colspan="5">'
                       '<div class="unit-sep"></div></td></tr>')
        elif 'сноска' in r:
            cls = 'cmt pw' if r.get('про силу') else 'cmt'
            out.append('            <tr class="%s"><td colspan="5">%s</td></tr>'
                       % (cls, текст(r['сноска'])))
        else:
            h = ВЫСОТА_ИКОНКИ[r['размер']]
            кадр = ('<img src="../%s" style="height: %.1fmm;" alt="">' % (esc(r['иконка']), h)
                    if r.get('иконка') else
                    '<div class="noimg" style="height: %.1fmm;">нет файла</div>' % h)
            ярлык = ''
            if r.get('группа'):                            # подпись группы на всю её высоту
                span = 0
                for q in отряды[i:]:
                    if 'имя' not in q: break
                    if q is not r and q.get('группа'): break
                    span += 1
                ярлык = ('<td class="group-label" rowspan="%d">%s</td>'
                         % (span, esc(r['группа'])))
            out.append('            <tr>\n'
                       '              <td class="u-icon">%s'
                       '<div class="unit-cap" data-uid="%s">%s</div></td>%s\n'
                       '              <td class="stat count">%s</td>'
                       '<td class="stat">%s</td>'
                       '<td class="stat power">%s</td>\n'
                       '            </tr>'
                       % (кадр, attr(r['имя']), esc(r['имя']), ярлык,
                          esc(r['количество']), esc(r['стоимость']), esc(r['сила'])))
    return '\n'.join(out)


def линии_привязок(свойства, заголовки, центры):
    """Запасные линии: печатаются, если в браузере не выполнится скрипт шаблона.
    Скрипт пересчитает их точнее — по реальному положению текста."""
    out = []
    for p, ya in zip(свойства, заголовки):
        отряд = p.get('отряд')
        if not отряд or отряд not in центры: continue
        yu = BODY_TOP + центры[отряд]
        out.append('<polyline points="%.1f,%.1f %.1f,%.1f %.1f,%.1f %.1f,%.1f"/>\n'
                   '      <circle cx="%.1f" cy="%.1f" r="0.9"/>'
                   % (X_ABIL_R, ya, X_ABIL_R + 2.5, ya,
                      X_ABIL_R + 2.5, yu, X_TABLE + 4, yu, X_ABIL_R, ya))
    return '\n      '.join(out)


# ══════════════════════════════════════════════════════════════ СЛОТЫ
def подставить(шаблон, слот, содержимое):
    начало, конец = '<!--#%s-->' % слот, '<!--/#%s-->' % слот
    pat = re.compile(re.escape(начало) + '.*?' + re.escape(конец), re.S)
    новый, n = pat.subn(lambda m: начало + содержимое + конец, шаблон)
    if n == 0:
        raise SystemExit('в шаблоне нет слота «%s»' % слот)
    return новый


def собрать(d, шаблон):
    высота_табл, центры = раскладка_таблицы(d['отряды'])
    отступы, заголовки, перелив = раскладка_свойств(d['свойства'], центры)
    лог = '../../art/logos/' + esc(d['логотип'])
    абзацы = ''.join('\n      <p>%s</p>' % esc(x) for x in d['оборот']['как играть'])
    # Оборот: иллюстрация из art/illustrations/ и блок «Как играть против» —
    # оба необязательны. Без них печатается заглушка 52 × 52 и один блок советов.
    ил = d['оборот'].get('иллюстрация')
    иллюстрация = ('<img src="../../art/illustrations/%s" alt="">' % attr(ил)) if ил \
        else 'иллюстрация фракции<br>52 × 52 мм'
    пр = d['оборот'].get('как играть против')
    против = ('\n    <div class="guide-title">Как играть против данной фракции</div>'
              '\n    <div class="guide">' + ''.join('\n      <p>%s</p>' % esc(x) for x in пр)
              + '\n    </div>\n  ') if пр else ''

    s = шаблон
    for слот, знач in [
        ('название',   esc(d['название'])),
        # Значок ресурса в бочке: по умолчанию капля нефти (barrel.png).
        # Фракция может заменить его своим — Moon Systems печатает ³He.
        ('бочка',      '<img src="%s" alt="Бочка — деление 0">' % attr(d.get('бочка', 'barrel.png'))),
        ('логотип',    '<img class="logo-wm" src="%s" alt="">' % лог),
        ('подготовка', '\n' + блок_подготовки(d['подготовка']) + '\n'),
        ('блоки',      '\n' + блоки_шагов(d['блоки']) + '\n'),
        ('свойства',   '\n' + блоки_свойств(d['свойства'], отступы) + '\n'),
        ('отряды',     '\n' + строки_таблицы(d['отряды']) + '\n'),
        ('связи',      '\n      ' + линии_привязок(d['свойства'], заголовки, центры) + '\n    '),
        ('лор',        esc(d['оборот']['лор'])),
        ('как-играть', абзацы + '\n    '),
        ('иллюстрация', иллюстрация),
        ('против',     против),
    ]:
        s = подставить(s, слот, знач)
    return s, высота_табл, перелив


def main():
    фильтр = sys.argv[1] if len(sys.argv) > 1 else ''
    шаблон = io.open(TPL_FILE, encoding='utf-8').read()
    файлы = sorted(f for f in os.listdir(DATA_DIR) if f.endswith('.json'))
    if not файлы:
        raise SystemExit('в папке «Данные» нет ни одного .json')
    не_собраны = []
    for f in файлы:
        if фильтр and фильтр.lower() not in f.lower(): continue
        d = json.load(io.open(os.path.join(DATA_DIR, f), encoding='utf-8'))
        ошибки = проверить_кавычки(d, f)
        if ошибки:
            print('\n'.join(ошибки))
            не_собраны.append(f)
            continue
        s, высота_табл, перелив = собрать(d, шаблон)
        имя = 'Планшет — %s.html' % d['название']
        io.open(os.path.join(ROOT, имя), 'w', encoding='utf-8').write(s)
        флаг = '  ← свойства поджаты' if перелив > 0 else ''
        print('%-28s таблица %5.1f мм из %.0f%s' % (d['название'], высота_табл, ROW_BODY, флаг))
    if не_собраны:
        raise SystemExit('не собраны из-за кавычек (нужны “ ”, D-075): ' + ', '.join(не_собраны))


if __name__ == '__main__':
    main()
