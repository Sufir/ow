# Find all safe-zone blocks for front cards
# We have 11 cards. We can replace them sequentially.
pattern = r'<div class="safe-zone">\s*<div class="title">.*?</div>\s*<div class="flavor">.*?</div>\s*<div class="illustration"></div>\s*<div class="properties">.*?</div>\s*</div>'
matches = list(re.finditer(pattern, content, flags=re.DOTALL))

if len(matches) != 11:
    print(f"Error: Found {len(matches)} cards, expected 11.")
    exit(1)

new_content = content
offset = 0

for i, col in enumerate(colonels):
    props_html = ""
    for j, prop in enumerate(col['props']):
        style = ' style="display: inline-block; margin-top: 2mm;"' if j > 0 else ''
        props_html += f'''
              <div class="prop-name"{style}>{prop['name']}</div>
              <div class="prop-cond">{prop['cond']}</div>
              <div class="prop-desc">{prop['desc']}</div>'''
              
    card_html = f'''<div class="safe-zone">
            <div class="title">{col['title']}</div>
            <div class="flavor">{col['flavor']}</div>
            <div class="illustration"></div>
            <div class="properties">{props_html}
            </div>
          </div>'''
          
    start = matches[i].start() + offset
    end = matches[i].end() + offset
    new_content = new_content[:start] + card_html + new_content[end:]
    offset += len(card_html) - (end - start)

with open('/workspace/UniqueColonel/index.html', 'w', encoding='utf-8') as f:
    f.write(new_content)

print("Successfully updated cards.")
